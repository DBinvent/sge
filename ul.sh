#!/bin/bash

cargo metadata --format-version=1 | jq > license.json
echo "RDBM powered by libraries tagged with those license:" > llic
grep \"license\" license.json | sort | uniq | grep -v null  >> llic
sed -i 's/"license": /-/g' llic
sed -i 's/  //g' llic
echo ""  >> llic

if [ $# -gt 0 ]; then
echo "From those authors:"  >> llic

grep '"name":' license.json | grep -v rdbm > alt
sed -i 's/"name": /-/g' alt
sed -i 's/  //g' alt
cat alt | sort | uniq  >>  llic

echo ""  >> llic

fi

grep '"license": null' -B4  license.json | grep name | grep -v "rdbm\|ring\|webpki\|fuchsia" > alt
sed -i 's/"name": /-/g' alt
sed -i 's/  //g' alt
asz=$(wc -l alt | cut -d " " -f1)
if [ $asz -gt 0 ]; then
echo "From those authors: with undefined license"  >> llic
cat alt >> llic
fi
rm alt

echo "https://github.com/briansmith/ring/blob/main/LICENSE" >> llic
echo "https://github.com/briansmith/webpki/blob/main/LICENSE" >> llic
echo "https://fuchsia.googlesource.com/fuchsia/+/refs/heads/main/LICENSE" >> llic

echo ""  >> llic
echo "This file been autogenerated using 'cargo metadata' on every run"  >> llic
echo ""  >> llic
echo "Thanks to every commuter, the license to 'rdbm' will be free for personal use!"  >> llic

mv llic lib-licenses.txt

rm license.json
