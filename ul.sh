#!/bin/bash

cargo metadata --format-version=1 | jq > license.json
echo "RDBM use libraries tagged with those license:" > lt
grep \"license\" license.json | sort | uniq | grep -v null  >> lt
sed -i 's/"license": /-/g' lt
sed -i 's/  //g' lt
echo ""  >> lt

if [ $# -gt 0 ]; then
echo "From those authors:"  >> lt

grep '"name":' license.json | grep -v rdbm > alt
sed -i 's/"name": /-/g' alt
sed -i 's/  //g' alt
cat alt | sort | uniq  >>  lt

echo ""  >> lt

fi

grep '"license": null' -B4  license.json | grep name | grep -v "rdbm\|ring\|webpki\|fuchsia" > alt
sed -i 's/"name": /-/g' alt
sed -i 's/  //g' alt
asz=$(wc -l alt | cut -d " " -f1)
if [ $asz -gt 0 ]; then
echo "From those authors: with undefined license"  >> lt
cat alt >> lt
fi
rm alt

echo "https://github.com/briansmith/ring/blob/main/LICENSE" >> lt
echo "https://github.com/briansmith/webpki/blob/main/LICENSE" >> lt
echo "https://fuchsia.googlesource.com/fuchsia/+/refs/heads/main/LICENSE" >> lt

echo ""  >> lt
echo "This file been autogenerated using 'cargo metadata' on every run"  >> lt
echo ""  >> lt
echo "Thanks to every commuter, the license to 'rdbm' will be free for personal use!"  >> lt

mv lt lib-licenses.txt

rm license.json
